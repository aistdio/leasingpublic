CREATE TABLE autoleasing_core.contracts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    car_vin VARCHAR(17) NOT NULL,
    client_id BIGINT NOT NULL,
    duration_in_months SMALLINT NOT NULL,
    down_payment DECIMAL(20, 2) NOT NULL,
    interest_rate DECIMAL(5, 2) NOT NULL,
    monthly_payment DECIMAL(20, 2) NOT NULL,
    status VARCHAR(100) NOT NULL,
    CONSTRAINT fk_contracts_car FOREIGN KEY (car_vin) REFERENCES autoleasing_core.cars(vin),
    CONSTRAINT fk_contracts_client FOREIGN KEY (client_id) REFERENCES autoleasing_core.clients(id)
);

ALTER TABLE autoleasing_core.payments
ADD CONSTRAINT fk_payments_contract FOREIGN KEY (contract_id) REFERENCES autoleasing_core.contracts(id);

CREATE INDEX idx_contracts_client_id ON autoleasing_core.contracts(client_id);
CREATE INDEX idx_payments_contract_id ON autoleasing_core.payments(contract_id);